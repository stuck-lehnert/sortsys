export function proposalOperationLabel(locale: Locale, path: string): string | null {
  return operationLabels[locale][path] ?? null;
}

export function proposalFieldLabel(locale: Locale, field: string): string {
  return fieldLabels[locale][field] ?? field.replace(/([a-z])([A-Z])/g, '$1 $2');
}

export function proposalValueLabel(locale: Locale, value: string): string | null {
  return valueLabels[locale][value] ?? null;
}
