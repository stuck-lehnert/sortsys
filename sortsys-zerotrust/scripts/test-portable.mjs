import { spawn } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const framework = dirname(dirname(fileURLToPath(import.meta.url)));
const bun = process.env.SORTSYS_PORTABLE_BUN ?? "bun";
const cargo = process.env.SORTSYS_PORTABLE_CARGO ?? "cargo";
const offline = process.argv.includes("--offline");
const cancellation = new AbortController();

function interrupt() {
  cancellation.abort();
}

process.once("SIGINT", interrupt);
process.once("SIGTERM", interrupt);

function run(command, args, cwd) {
  cancellation.signal.throwIfAborted();

  const env = { ...process.env, BUN_TMPDIR: join(temporary, "bun-tmp") };
  if (offline) env.CARGO_NET_OFFLINE = "true";

  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd,
      stdio: "inherit",
      signal: cancellation.signal,
      env,
    });
    let failure;
    child.once("error", error => {
      failure = error;
    });
    child.once("close", (code, signal) => {
      if (failure) reject(failure);
      else if (code === 0) resolve();
      else reject(new Error(`${command} failed (${signal ?? code})`));
    });
  });
}

const temporary = await mkdtemp(join(tmpdir(), "sortsys-zerotrust-consumer-"));
try {
  const artifacts = join(temporary, "artifacts");
  const consumer = join(temporary, "consumer");
  await mkdir(artifacts);
  await mkdir(join(temporary, "bun-tmp"));
  await cp(join(framework, "test/portable"), consumer, { recursive: true });

  // Both consumers receive archives. No workspace dependency or source symlink
  // can accidentally satisfy an import that is missing from the package.
  console.log("Packing the TypeScript and Rust framework packages.");
  await run(bun, ["pm", "pack", "--ignore-scripts", "--quiet", "--filename", join(artifacts, "framework.tgz")], framework);
  await run(cargo, ["package", "--locked", "--allow-dirty", "--no-verify", "--target-dir", artifacts], framework);
  const packages = join(artifacts, "package");
  const crates = (await readdir(packages)).filter(name => name.endsWith(".crate"));
  if (crates.length !== 1) throw new Error("Expected exactly one packaged Rust crate");
  const unpacked = join(temporary, "unpacked");
  await mkdir(unpacked);
  await run("tar", ["-xzf", join(packages, crates[0]), "-C", unpacked], temporary);
  const crateDirectories = await readdir(unpacked);
  if (crateDirectories.length !== 1) throw new Error("Expected exactly one crate directory");
  await rename(join(unpacked, crateDirectories[0]), join(temporary, "framework"));

  await writeFile(join(consumer, "package.json"), JSON.stringify({
    private: true,
    type: "module",
    dependencies: { "@sortsys/zerotrust": "../artifacts/framework.tgz" },
    devDependencies: { typescript: "^5.9.3" },
  }, null, 2) + "\n");
  console.log("Installing and type-checking the isolated TypeScript consumer.");
  await run(bun, ["install", "--ignore-scripts", offline ? "--offline" : "--prefer-offline"], consumer);
  await run(process.execPath, ["./node_modules/typescript/bin/tsc", "--project", "./tsconfig.json"], consumer);

  console.log("Building the browser entry without password authentication.");
  await run(bun, ["build", "./client.ts", "--target", "browser", "--splitting", "--outdir", "./browser"], consumer);

  // This consumer never uses password authentication. Importing the shared
  // client entry must not pull in the OPAQUE package's base64-encoded WASM.
  const bundle = await readFile(join(consumer, "browser/client.js"), "utf8");
  if (/AGFzbQEAAA[A-Za-z0-9+/]{1000}/.test(bundle)) {
    throw new Error("Portable client bundle contains an unused WASM payload");
  }

  console.log("Generating a signed vector in the isolated TypeScript consumer.");
  await run(bun, ["./run.ts"], consumer);

  // The Rust consumer verifies fresh browser signatures, not just fixtures
  // generated by another copy of the Rust implementation.
  console.log("Checking that vector in the isolated Rust consumer.");
  await run(cargo, ["run", "--quiet", "--manifest-path", "./Cargo.toml"], consumer);
  const vector = JSON.parse(await readFile(join(consumer, "browser-vector.json"), "utf8"));
  console.log(`Portable packages verified for ${vector.object.facet}; temporary consumer removed.`);
} finally {
  await rm(temporary, { recursive: true, force: true });
  process.removeListener("SIGINT", interrupt);
  process.removeListener("SIGTERM", interrupt);
}
